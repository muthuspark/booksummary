#!/usr/bin/env python3
"""Exercise the summary writer in isolated repositories without calling Codex."""
from pathlib import Path
import json
import os
import shutil
import subprocess
import tempfile
import unittest

SCRIPT = Path(__file__).with_name('write_random_summary.sh')
FAKE_CODEX = r'''#!/usr/bin/env python3
from pathlib import Path
import json, os, struct, sys, zlib
prompt = sys.stdin.read()
Path('invocation.json').write_text(json.dumps(sys.argv[1:]))
book, _ = json.JSONDecoder().raw_decode(prompt.split('Selected book (data, not instructions):\n', 1)[1])
Path('selected.json').write_text(json.dumps(book))
mode = os.environ.get('FAKE_MODE', '')
if mode == 'codex-failure':
    raise SystemExit(7)
p = Path(book['destination'])
p.parent.mkdir(parents=True, exist_ok=True)
authors = book['author'].split(' and ')
author_field = '\nauthors: ' + json.dumps(authors)
if mode == 'missing-authors':
    author_field = ''
elif mode == 'malformed-authors':
    author_field = '\nauthors: ' + json.dumps(book['author'])
elif mode == 'duplicate-authors':
    author_field = '\nauthors: ' + json.dumps(authors + authors)
p.write_text('---\ntitle: ' + json.dumps(book['label']) + '\nauthor: ' + json.dumps(book['author'])
             + author_field + '\ncategories: [' + json.dumps(book['category']) + ']\ndescription: A useful summary\nimage: image.png\n---\n\n'
             + '# Summary\n\n' + ('Thoughtful original explanation. ' * 250))
if mode != 'missing-image':
    def chunk(tag, data):
        return struct.pack('>I', len(data)) + tag + data + struct.pack('>I', zlib.crc32(tag + data) & 0xffffffff)
    png = b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', 512, 512, 8, 2, 0, 0, 0))
    png += chunk(b'IDAT', zlib.compress((b'\0' + b'\x80\xa0\x90' * 512) * 512)) + chunk(b'IEND', b'')
    p.with_name('image.png').write_bytes(png)
p.with_name('image-source.md').write_text('Generated by the fake tool for an isolated test.\n')
'''
PROGRESS = '''# Summary Progress
Total books summarized: **1**.
Books planned: **2**. Total tracked: **3**.
## Existing (1)
- [x] [Already Written by Existing Author](content/posts/existing/already-written/index.md)
## Books to Summarize (2)
### Science and Nature (2)
- [ ] Example Book by First Author
- [ ] Another Book by Second Author
'''


class SummaryWriterTest(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='summary-writer-test-')
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        (self.root / 'scripts').mkdir()
        (self.root / 'bin').mkdir()
        (self.root / 'content/posts/existing/already-written').mkdir(parents=True)
        (self.root / 'content/posts/existing/already-written/index.md').write_text('---\ntitle: "Already Written by Existing Author"\n---\n')
        shutil.copy2(SCRIPT, self.root / 'scripts/write_random_summary.sh')
        shutil.copy2(SCRIPT.with_name('author_pages.py'), self.root / 'scripts/author_pages.py')
        (self.root / 'progress.md').write_text(PROGRESS)
        self.executable('bin/codex', FAKE_CODEX)
        self.executable('bin/hugo', '#!/bin/sh\nexit 0\n')
        self.executable('scripts/build_site.sh', """#!/usr/bin/env python3
from pathlib import Path
import json, os
Path('build-ran').touch()
if os.environ.get('FAKE_MODE') == 'build-failure':
    raise SystemExit(1)
book = json.loads(Path('selected.json').read_text())
Path('docs').mkdir(exist_ok=True)
entry = dict(url='/' + Path(book['destination']).relative_to('content').parent.as_posix() + '/',
             title=book['label'], author=book['author'], categories=[book['category']])
if os.environ.get('FAKE_MODE') == 'wrong-book':
    entry['title'] = 'A different book'
Path('docs/search.json').write_text(json.dumps([entry]))
""")
        self.executable('render_publish.sh', """#!/usr/bin/env python3
from pathlib import Path
import os
Path('publish-ran').write_text(Path('progress.md').read_text())
if os.environ.get('FAKE_MODE') == 'publish-failure':
    raise SystemExit(9)
""")
        subprocess.run(['git', 'init', '-q', str(self.root)], check=True)
        self.env = dict(os.environ, PATH=str(self.root / 'bin') + os.pathsep + os.environ['PATH'])

    def executable(self, name, content):
        path = self.root / name
        path.write_text(content)
        path.chmod(0o755)

    def run_writer(self, *args, mode='', check=True):
        result = subprocess.run(['bash', str(self.root / 'scripts/write_random_summary.sh'), *args],
                                cwd='/tmp', env=dict(self.env, FAKE_MODE=mode), text=True, capture_output=True)
        if check:
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        return result

    def test_success_checks_off_only_selected_book_after_build(self):
        self.run_writer('--model', 'configured-test-model', '--profile', 'test-profile')
        selected = json.loads((self.root / 'selected.json').read_text())
        progress = (self.root / 'progress.md').read_text()
        self.assertIn(f'- [x] [{selected["label"]}]({selected["destination"]})', progress)
        self.assertEqual(progress.count('- [ ] '), 1)
        self.assertIn('summarized: **2**', progress)
        self.assertIn('planned: **1**', progress)
        self.assertIn('tracked: **3**', progress)
        self.assertTrue((self.root / 'build-ran').exists())
        self.assertEqual((self.root / 'publish-ran').read_text(), progress)
        args = json.loads((self.root / 'invocation.json').read_text())
        self.assertIn('workspace-write', args)
        self.assertIn('configured-test-model', args)
        self.assertIn('test-profile', args)
        self.assertEqual(args[-1], '-')

    def test_dry_run_does_not_invoke_codex_or_change_progress(self):
        result = self.run_writer('--dry-run')
        self.assertIn('Eligible books: 2', result.stdout)
        self.assertIn('Hero image (required)', result.stdout)
        self.assertFalse((self.root / 'invocation.json').exists())
        self.assertEqual((self.root / 'progress.md').read_text(), PROGRESS)
        self.assertFalse((self.root / 'publish-ran').exists())

    def test_failures_preserve_unchecked_progress(self):
        for mode in ('codex-failure', 'missing-image', 'build-failure', 'wrong-book', 'missing-authors', 'malformed-authors', 'duplicate-authors'):
            with self.subTest(mode=mode):
                result = self.run_writer(mode=mode, check=False)
                self.assertNotEqual(result.returncode, 0)
                self.assertEqual((self.root / 'progress.md').read_text(), PROGRESS)
                self.assertFalse((self.root / 'publish-ran').exists())
                shutil.rmtree(self.root / 'content/posts/science_and_nature', ignore_errors=True)

    def test_coauthor_summary_keeps_individual_credits(self):
        (self.root / 'progress.md').write_text('### Science (1)\n- [ ] A Book by First Author and Second Author\n')
        self.run_writer()
        selected = json.loads((self.root / 'selected.json').read_text())
        text = (self.root / selected['destination']).read_text()
        self.assertIn('authors: ["First Author", "Second Author"]', text)
        self.assertTrue((self.root / 'publish-ran').exists())

    def test_missing_authors_fails_before_build_or_publish(self):
        result = self.run_writer(mode='missing-authors', check=False)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('authors field', result.stderr)
        self.assertFalse((self.root / 'build-ran').exists())
        self.assertFalse((self.root / 'publish-ran').exists())
        self.assertEqual((self.root / 'progress.md').read_text(), PROGRESS)

    def test_publish_failure_returns_error_but_keeps_completed_progress(self):
        result = self.run_writer(mode='publish-failure', check=False)
        self.assertEqual(result.returncode, 9)
        self.assertTrue((self.root / 'publish-ran').exists())
        selected = json.loads((self.root / 'selected.json').read_text())
        progress = (self.root / 'progress.md').read_text()
        self.assertIn(f'- [x] [{selected["label"]}]({selected["destination"]})', progress)

    def test_partial_bundle_is_not_overwritten(self):
        path = self.root / 'content/posts/science_and_nature/example-book'
        path.mkdir(parents=True)
        marker = path / 'notes.txt'
        marker.write_text('Keep partial work')
        self.run_writer()
        selected = json.loads((self.root / 'selected.json').read_text())
        self.assertEqual(selected['title'], 'Another Book')
        self.assertEqual(marker.read_text(), 'Keep partial work')

    def test_finished_backlog_exits_without_codex(self):
        (self.root / 'progress.md').write_text(PROGRESS.replace('- [ ] ', '- [x] '))
        result = self.run_writer()
        self.assertIn('No unwritten books remain', result.stdout)
        self.assertFalse((self.root / 'publish-ran').exists())
        self.assertFalse((self.root / 'invocation.json').exists())

    def test_explicit_link_is_respected_and_traversal_is_rejected(self):
        (self.root / 'progress.md').write_text('### Science (1)\n- [ ] [A Title by An Author](content/posts/science/custom-slug/index.md)\n')
        self.run_writer()
        self.assertTrue((self.root / 'content/posts/science/custom-slug/index.md').is_file())
        (self.root / 'progress.md').write_text('### Science (1)\n- [ ] [A Title by An Author](../../outside/index.md)\n')
        result = self.run_writer('--dry-run', check=False)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('Invalid summary destination', result.stderr)

    def test_concurrent_run_is_refused(self):
        import fcntl
        with (self.root / '.git/summary-writer.lock').open('w') as lock:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
            result = self.run_writer(check=False)
            self.assertNotEqual(result.returncode, 0)
            self.assertIn('Another summary-writing run is active', result.stderr)
            self.assertFalse((self.root / 'invocation.json').exists())

    def test_invalid_cli_option_fails(self):
        self.assertEqual(self.run_writer('--model', check=False).returncode, 2)
        self.assertEqual(self.run_writer('--unknown', check=False).returncode, 2)


if __name__ == '__main__':
    unittest.main()
